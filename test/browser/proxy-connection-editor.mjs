import assert from 'node:assert/strict';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { readFileSync } from 'node:fs';
import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args: ['--allow-file-access-from-files'] });
try {
  const page = await browser.newPage();
  await page.setViewport({ width: 360, height: 780 });
  await page.setJavaScriptEnabled(false);
  await page.goto(pathToFileURL(path.resolve('src/common/pages/options/index.html')).href);
  await page.setJavaScriptEnabled(true);
  await page.addStyleTag({ path: path.resolve('src/common/pages/options/proxy-connection-editor.css') });
  const authVisibility = await page.evaluate(async () => {
    const { createProxyEditDraft, renderProxyConnectionEditor } = await import('./proxy-connection-editor.js');
    const profile = { name: 'Test', endpoint: 'HTTPS host.test:443' };
    const draft = createProxyEditDraft(profile, profile.endpoint);
    const writes = [];
    const render = () => renderProxyConnectionEditor({ profile, draft, onSubmit: payload => { writes.push(payload); }, onCancel() {} });
    document.body.replaceChildren(render());
    const auth = document.querySelector('[name=hasAuth]');
    const username = document.querySelector('[name=username]'), password = document.querySelector('[name=password]');
    const snapshot = () => ({ checked: auth.checked, visible: Boolean(username.getClientRects().length || password.getClientRects().length), disabled: username.disabled && password.disabled });
    const initial = snapshot();
    auth.click();
    const enabled = snapshot();
    username.value = 'fixture-user'; username.dispatchEvent(new Event('input'));
    password.value = ' fixture password '; password.dispatchEvent(new Event('input'));
    auth.click();
    const off = snapshot();
    document.querySelector('form').requestSubmit();
    await new Promise(resolve => setTimeout(resolve, 0));
    auth.click();
    const restored = { ...snapshot(), username: username.value, password: password.value };
    document.body.replaceChildren(render());
    const refreshed = { checked: document.querySelector('[name=hasAuth]').checked, visible: Boolean(document.querySelector('[name=username]').getClientRects().length), username: document.querySelector('[name=username]').value, password: document.querySelector('[name=password]').value };
    return { initial, enabled, off, restored, refreshed, writes };
  });
  assert.deepEqual(authVisibility.initial, { checked: false, visible: false, disabled: true }, 'no saved auth: unchecked with hidden credentials');
  assert.deepEqual(authVisibility.enabled, { checked: true, visible: true, disabled: false }, 'checking auth reveals usable fields');
  assert.deepEqual(authVisibility.off, { checked: false, visible: false, disabled: true }, 'unchecking auth hides the fields again');
  assert.deepEqual(authVisibility.writes, [{ proxy: 'HTTPS host.test:443', name: 'Test' }], 'hidden credentials must not be submitted');
  assert.deepEqual(authVisibility.restored, { checked: true, visible: true, disabled: false, username: 'fixture-user', password: ' fixture password ' });
  assert.deepEqual(authVisibility.refreshed, { checked: true, visible: true, username: 'fixture-user', password: ' fixture password ' }, 'refresh preserves checkbox, fields and exact draft');
  const result = await page.evaluate(async () => {
    const { createProxyEditDraft, renderProxyConnectionEditor } = await import('./proxy-connection-editor.js');
    const profile = { id: 'synthetic', name: 'Test', endpoint: 'HTTPS [2001:db8::1]:443' };
    const draft = createProxyEditDraft(profile, 'HTTPS user%40mail:%20pass%3Aword%20@[2001:db8::1]:443');
    const original = { ...draft };
    const writes = [];
    const render = () => renderProxyConnectionEditor({ profile, draft, onSubmit: payload => { writes.push(payload); throw new Error('Synthetic save failure'); }, onCancel() {} });
    document.body.replaceChildren(render());
    document.querySelector('form').requestSubmit();
    await new Promise(resolve => setTimeout(resolve, 0));
    const retained = { ...draft };
    const passwordType = document.querySelector('[name=password]').type;
    const change = (name, value) => { const input = document.querySelector(`[name=${name}]`); input.value = value; input.dispatchEvent(new Event('input', { bubbles: true })); };
    change('username', '');
    const missingUsername = document.querySelector('[name=username]').validity.valueMissing;
    const validHost = document.querySelector('[name=host]').validity.valid;
    document.querySelector('form').requestSubmit();
    change('username', 'user@mail');
    change('name', `  ${'🦊'.repeat(32)}  `);
    change('host', '2001:db8::2');
    change('password', '  new : @ %  ');
    draft.error = 'Synthetic backend validation rejection';
    document.body.replaceChildren(render());
    const backendError = document.querySelector('[role=status]').textContent;
    const refreshed = document.querySelector('[name=password]').value;
    document.querySelector('form').requestSubmit();
    await new Promise(resolve => setTimeout(resolve, 0));
    change('protocol', 'SOCKS5');
    document.querySelector('form').requestSubmit();
    const socksError = document.querySelector('[name=protocol]').validationMessage;
    return { backendError, original, retained, passwordType, refreshed, writes, socksError, missingUsername, validHost, labels: [...document.querySelectorAll('input,select')].every(input => input.labels.length), overflow: document.documentElement.scrollWidth > innerWidth };
  });
  assert.equal(result.backendError, 'Synthetic backend validation rejection');
  assert.equal(result.original.password, ' pass:word ');
  assert.equal(result.original.username, 'user@mail');
  assert.equal(result.passwordType, 'password');
  assert.deepEqual(result.retained, result.original);
  assert.equal(result.refreshed, '  new : @ %  ');
  assert.equal(result.writes.length, 2);
  assert.equal(result.missingUsername, true);
  assert.equal(result.validHost, true);
  assert.equal(result.writes[1].name, '🦊'.repeat(32));
  assert.equal(result.writes[0].proxy, 'HTTPS user%40mail:%20pass%3Aword%20@[2001:db8::1]:443');
  assert.equal(result.writes[1].proxy, 'HTTPS user%40mail:%20%20new%20%3A%20%40%20%25%20%20@[2001:db8::2]:443');
  assert.match(result.socksError, /SOCKS/);
  assert.equal(result.labels, true);
  assert.equal(result.overflow, false);
  for (const locale of ['ru', 'en']) {
    const catalog = JSON.parse(readFileSync(path.resolve(`src/common/_locales/${locale}/messages.json`), 'utf8'));
    const localized = await page.evaluate(async messages => {
      globalThis.chrome.i18n = { getMessage: key => messages[key]?.message || '' };
      const { createProxyEditDraft, renderProxyConnectionEditor } = await import('./proxy-connection-editor.js');
      const profile = { name: 'Test', endpoint: 'HTTPS host.test:443' };
      const draft = createProxyEditDraft(profile, 'HTTPS host.test:443');
      draft.error = 'Backend rejection retained';
      const render = busy => renderProxyConnectionEditor({ profile, draft, busy, onSubmit() {}, onCancel() {} });
      document.body.replaceChildren(render(false));
      const labels = [...document.querySelectorAll('.form-label')].map(label => label.textContent);
      const legend = document.querySelector('legend').textContent;
      const initialStatus = document.querySelector('[role=status]').textContent;
      const name = document.querySelector('[name=name]'); name.value = 'x'.repeat(33); name.dispatchEvent(new Event('input'));
      const nameError = name.validationMessage;
      document.body.replaceChildren(render(true));
      return { labels, legend, initialStatus, nameError, busy: document.querySelector('fieldset').disabled, saving: document.querySelector('[type=submit]').textContent };
    }, catalog);
    assert.deepEqual(localized.labels, ['proxyConnectionName', 'proxyConnectionProtocol', 'proxyConnectionHost', 'proxyConnectionPort', 'proxyConnectionUsername', 'proxyConnectionPassword'].map(key => catalog[key].message));
    assert.equal(localized.legend, catalog.proxyEditConnection.message);
    assert.equal(localized.initialStatus, 'Backend rejection retained');
    assert.equal(localized.nameError, catalog.proxyConnectionInvalidName.message);
    assert.equal(localized.busy, true);
    assert.equal(localized.saving, catalog.proxyConnectionSaving.message);
  }
  console.log('Proxy connection editor: Chromium DOM, ru/en localization, backend draft.error, credentials, exact spaces, IPv6, failed-save/refresh draft, SOCKS rejection, labelled controls, 360px: PASS');
} finally { await browser.close(); }
